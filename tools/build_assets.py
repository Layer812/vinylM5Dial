"""Build embedded RGB565 labels from artwork supplied by the project owner.
Explicit 8.3-key matching: missing mappings always fall back to gold.
"""
from pathlib import Path
from PIL import Image
import csv
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets'
OUT = ROOT / 'src' / 'label_assets.h'
SIZE = 122


def key(s):
    s=s.strip().upper()
    if '/' in s or '\\' in s: raise ValueError('Use filename, not paths: '+s)
    if '.' in s:
        a,b=s.split('.',1)
        if not (1 <= len(a) <= 8 and 1 <= len(b) <= 3):
            raise ValueError('Only 8.3 keys supported: '+s)
    else:
        a,b=s,''
        if not 1 <= len(a) <= 8: raise ValueError('Max 8 base-name characters: '+s)
    if not re.fullmatch(r'[A-Z0-9_~\-$]+', a):
        raise ValueError('Use ASCII 8.3 filenames: '+s)
    if b and not re.fullmatch(r'[A-Z0-9]{1,3}', b):
        raise ValueError('Invalid extension: '+s)
    return a.ljust(8) + b.ljust(3)

mapping={}
with (ASSETS/'labels.csv').open(encoding='utf-8-sig',newline='') as f:
    for row in csv.reader(f):
        if not row or not row[0].strip() or row[0].lstrip().startswith('#'): continue
        if len(row)!=2: raise ValueError('Expected NAME.MP3,00: '+repr(row))
        k=key(row[0]); v=int(row[1].strip(),10)
        if k in mapping: raise ValueError('Duplicate key '+k)
        if not 0<=v<18: raise ValueError('Artwork index must be 00..17')
        mapping[k]=v
labels=[]
for i in range(18):
    img=Image.open(ASSETS/f'label_{i:02d}.png').convert('RGB')
    if img.size!=(SIZE,SIZE):
        img=img.resize((SIZE,SIZE),Image.Resampling.LANCZOS)
    raw=[]
    for r,g,b in img.getdata():
        raw.append(((r&0xf8)<<8)|((g&0xfc)<<3)|(b>>3))
    labels.append(raw)
with OUT.open('w',encoding='ascii') as f:
    f.write('// GENERATED by tools/build_assets.py; do not edit manually.\n')
    f.write('#pragma once\n#include <stdint.h>\n')
    f.write('static constexpr int kArtworkCount = 18;\n')
    f.write('static constexpr int kArtworkWidth = 122;\n')
    f.write('static const uint16_t kArtwork[kArtworkCount][kArtworkWidth*kArtworkWidth] = {\n')
    for arr in labels:
        f.write(' {\n')
        for start in range(0,len(arr),20):
            f.write('  '+','.join(f'0x{val:04X}' for val in arr[start:start+20])+',\n')
        f.write(' },\n')
    f.write('};\n')
    f.write('struct LabelKeyMap{ char key[12]; uint8_t artwork; };\n')
    f.write('static const LabelKeyMap kLabelMap[] = {\n')
    for k,v in mapping.items():
        f.write(' {"'+k+'",'+str(v)+'},\n')
    f.write(' {"           ",255} // sentinel, not a valid file key\n};\n')
    f.write('static constexpr unsigned kLabelMapCount = '+str(len(mapping))+';\n')
print('Generated',OUT,'with',len(mapping),'mapped tracks, 18 artworks')
